use super::render_session::RenderSession;

/// Simple text-based overlay rendered directly into the pixel buffer.
/// Uses a minimal built-in 5x7 bitmap font.
pub struct Overlay;

impl Overlay {
    /// Render overlay text onto the display pixel buffer.
    pub fn render(session: &RenderSession, pixels: &mut [u32], width: u32) {
        let lines = Self::build_lines(session);
        let x_start = 8;
        let mut y_pos = 8;

        for line in &lines {
            Self::draw_string(pixels, width, x_start, y_pos, line);
            y_pos += 10;
        }
    }

    fn build_lines(session: &RenderSession) -> Vec<String> {
        vec![
            format!("Scene: {}", session.scene.name),
            format!("Camera: {} ({}/{})",
                session.current_camera_name(),
                session.state.camera_preset_index + 1,
                session.camera_preset_count(),
            ),
            format!("Quality: {}", session.state.quality.name()),
            format!("DOF: {}", session.state.dof.name()),
            format!("Deterministic: {}", if session.deterministic { "ON" } else { "OFF" }),
            format!("Samples: {}", session.sample_count()),
            String::new(),
            "Q=Quality  C=Camera  D=DOF  Esc=Quit".to_string(),
        ]
    }

    fn draw_string(pixels: &mut [u32], buf_width: u32, x: u32, y: u32, text: &str) {
        let mut cx = x;
        for ch in text.chars() {
            Self::draw_char(pixels, buf_width, cx, y, ch);
            cx += 6; // 5px wide + 1px gap
        }
    }

    fn draw_char(pixels: &mut [u32], buf_width: u32, x: u32, y: u32, ch: char) {
        let glyph = get_glyph(ch);
        let height = pixels.len() as u32 / buf_width;

        for (row, &bits) in glyph.iter().enumerate() {
            for col in 0..5u32 {
                if bits & (1 << (4 - col)) != 0 {
                    let px = x + col;
                    let py = y + row as u32;
                    if px < buf_width && py < height {
                        let idx = (py * buf_width + px) as usize;
                        // Draw with shadow for readability
                        if px + 1 < buf_width && py + 1 < height {
                            let shadow_idx = ((py + 1) * buf_width + px + 1) as usize;
                            pixels[shadow_idx] = 0x000000;
                        }
                        pixels[idx] = 0xFFFFFF;
                    }
                }
            }
        }
    }
}

